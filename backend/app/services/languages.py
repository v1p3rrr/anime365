"""Приведение языковых кодов дорожек к двухбуквенным.

Зачем библиотека, а не словарь. У одного языка бывает несколько трёхбуквенных
кодов: ISO 639-2 держит «библиографический» и «терминологический» варианты, и
они не совпадают. Только среди тех языков, у кого есть двухбуквенный код, таких
пар восемь: `ger`/`deu`, `fre`/`fra`, `chi`/`zho`, `cze`/`ces`, `gre`/`ell`,
`dut`/`nld`, `ice`/`isl`, `per`/`fas`. Ручной словарь на три языка не задваивал
`ja` и `jpn` только потому, что всё остальное молча выбрасывал: французская
дорожка (`fre`) до сих пор просто исчезала.

`iso639-lang` знает 8038 языков, из них 183 с двухбуквенным кодом, и понимает
как коды всех редакций, так и английские названия («Japanese»).

## Чего библиотека сделать не может

⚠️ **`jap` — это НЕ японский.** По ISO это код языка жаруара (Бразилия),
устаревший с 2007 года в пользу `jaa`. Библиотека честно бросает на нём
`DeprecatedLanguageValue` и никогда не даст `ja`.

Но в аниме-релизах `jap` пишут именно в значении «японский» — это устоявшаяся
небрежность, а не стандарт. Поэтому поверх библиотеки лежит короткий явный
список бытовых написаний. Он существует ровно для таких случаев и не должен
разрастаться: всё, что укладывается в стандарт, обязано идти через библиотеку.

Не удаляйте `jap` как «ошибку» — это осознанное отступление от ISO в пользу
того, что реально написано в файлах.
"""

from __future__ import annotations

import logging

from iso639 import Lang
from iso639.exceptions import DeprecatedLanguageValue, InvalidLanguageValue

log = logging.getLogger(__name__)

#: Написания, которых нет в стандарте, но которые встречаются в дорожках.
#: Ключи — уже приведённые к нижнему регистру и обрезанные строки.
NON_STANDARD: dict[str, str] = {
    # Формально — жаруара (см. модульную докстроку). Фактически в релизах
    # аниме это японский, и трактовать иначе значит потерять дорожку.
    "jap": "ja",
    # Встречается в дорожках, собранных на Windows-инструментах.
    "jpn-jp": "ja",
    "rus-ru": "ru",
    "eng-us": "en",
    "eng-gb": "en",
}

#: Коды, которые означают «язык не указан». Это не ошибка разбора, поэтому в
#: лог о них не пишем — иначе он забьётся на первой же большой библиотеке.
UNDETERMINED = {"und", "undetermined", "unknown", "zxx", "mis", "mul"}


def _lookup(value: str) -> Lang | None:
    try:
        return Lang(value)
    except (InvalidLanguageValue, DeprecatedLanguageValue):
        return None


def normalize_lang(raw: str | None) -> str | None:
    """Двухбуквенный код языка или `None`, если определить не удалось.

    `None` — нормальный исход, а не сбой: дорожка без языка встречается сплошь
    и рядом, и вызывающий код обязан это уметь.
    """
    if not raw:
        return None

    value = raw.strip().lower()
    if not value or value in UNDETERMINED:
        return None

    if value in NON_STANDARD:
        return NON_STANDARD[value]

    lang = _lookup(value) or _lookup(value.title())
    if lang is None:
        log.debug("Не удалось определить язык дорожки: %r", raw)
        return None

    # У части языков двухбуквенного кода не существует вовсе (их 183 из 8038).
    # Возвращаем трёхбуквенный: потерять язык хуже, чем показать длинный код.
    return lang.pt1 or lang.pt3 or None


def language_name(code: str | None) -> str | None:
    """Английское название языка — для подсказок, где кода мало."""
    if not code:
        return None
    lang = _lookup(code.strip()) or _lookup(code.strip().title())
    return lang.name if lang else None
