"""Виды перевода: что за ними стоит и что из этого следует.

В API вид лежит в `typeKind`, и набор значений там **шире**, чем в документации.
Кроме `voice`, `sub`, `raw` и `voiceOth` встречается `subv` — проверено на живых
данных, разбор в `claude/02-api-findings.md`.

## Что такое `subv`

Это **надписи и песни**, а не полный перевод. Установлено сравнением файла с
обычным `sub` той же серии (Yuru Yuri, серия 1):

| | `subv` (Yousei-raws) | `sub` (Advantage & Ambiente & GMC) |
|---|---|---|
| реплик | 139 | 472 |
| минут с репликами | 11 из 24 | 24 из 24 |
| стили | `op`, `ed`, `sign`, `title`, `staff` | `main` (363 реплики), `signs`, `OP`, `ED` |
| караоке (`\\k`) | 505 тегов | нет |

То есть реплики жмутся к первой-второй минуте (опенинг) и к двадцать
второй-двадцать третьей (эндинг), а между ними — редкие надписи. Дорожки
`main` там нет вовсе. Такое кладут поверх озвучки или смотрят те, кто понимает
речь на слух.

## Что из этого следует

**Считать `subv` теми же субтитрами нельзя.** Человек, включивший «Субтитры ·
RU», ждёт перевод реплик, а получил бы песни и вывески. По той же причине `subv`
не идёт в счётчики фоновой джобы: фильтр каталога «есть русские субтитры»
обязан отвечать про реплики.

**Прятать тоже нельзя.** Перевод существует, скачивается и кому-то нужен именно
такой. Поэтому он остаётся отдельным видом со своей подписью, а клиент такие
сочетания не фильтрует по настройке типов (см. `translationType()` — незнакомое
сочетание возвращает `null` и не прячется).

**Но по поведению это файл субтитров**, а не видео: у него есть `subtitlesUrl` с
настоящим `.ass`. Отсюда `SUBTITLE_KINDS` — по нему именование добавляет
языковой суффикс. Без этого скачанный `subv` лёг бы файлом без `.ru`, и Jellyfin
не понял бы его язык.
"""

from __future__ import annotations

#: Виды, у которых скачивается файл субтитров, а не видеодорожка.
#:
#: Именно от этого зависит языковой суффикс в имени файла: `.ru`, `.ja`, `.en`.
#: Проверять `kind == "sub"` мало — `subv` тоже субтитры.
SUBTITLE_KINDS = frozenset({"sub", "subv"})

#: Вид, означающий «только надписи и песни».
SIGNS_AND_SONGS = "subv"


def is_subtitle_kind(kind: str | None) -> bool:
    """Скачивается ли для этого вида файл субтитров."""
    return (kind or "").strip() in SUBTITLE_KINDS
