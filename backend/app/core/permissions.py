"""Права доступа.

Разграничение работает: у каждой учётной записи свой логин, пароль и набор прав,
и **каждый** эндпоинт под `/api/` либо требует права, либо внесён в короткий
список открытых с объяснением. За тем, чтобы новый маршрут не оказался открытым
по недосмотру, следит `tests/test_permissions_audit.py`: он читает объявления
роутеров и падает на любом, у кого нет ни проверки, ни записи в списке.

Главное правило, ради которого модуль вообще нужен: **проверка на сервере, а не
в интерфейсе**. Спрятать кнопку легко, но кнопка — не защита: тот же запрос
отправляется из консоли браузера одной строкой. Поэтому право проверяется в
зависимости эндпоинта, а скрытие кнопок в UI (хук `usePermissions`) — только
удобство поверх неё: интерфейс не должен предлагать то, что ответит отказом.

Права намеренно крупные. Дробить до отдельных действий («менять привязки, но не
запускать скан») смысла нет: это домашний сервис на несколько человек, и разница
между ролями здесь проходит по крупным границам — кто может тратить диск и
трафик, кто может менять общие настройки, а кто просто смотрит.

Деление — по последствиям, а не по разделам интерфейса. Одна страница может
требовать разных прав (на странице тайтла сходятся `catalog`, `watch`,
`downloads` и `library`), и это правильно: право отвечает на вопрос «что
случится», а не «где нажали».
"""

from __future__ import annotations

import logging
from enum import Enum

from fastapi import Depends, Request

from app.core import errors
from app.core.db import session_scope
from app.core.errors import ApiError
from app.models import DEFAULT_USER_ID, AppUser

log = logging.getLogger(__name__)


class Permission(str, Enum):
    """Категории действий, которые можно разрешить или запретить по отдельности.

    Порядок здесь — от безобидного к опасному, и в интерфейсе он такой же.
    """

    #: Видеть каталог, страницы тайтлов и состояние библиотеки. Право на
    #: чтение и ни на что больше.
    #:
    #: ⚠️ **Выдаётся всем, кто вошёл, и не отбирается.** Отдельным правом
    #: осталось потому, что эндпоинтам нужно чем-то различать «читать» и
    #: «менять» — но в интерфейсе галочки для него нет и быть не должно:
    #: учётная запись, которая может войти и ничего не увидеть, бессмысленна,
    #: а раздавать её каждому руками — лишний шаг с одним исходом.
    #: См. `IMPLICIT_PERMISSIONS` ниже.
    CATALOG = "catalog"

    #: Менять серверные настройки — токен, пути, расписания. Самое опасное:
    #: через настройки видно премиум-токен и задаются пути записи на диск.
    SETTINGS = "settings"

    #: Ставить загрузки в очередь и управлять ею. Тратит диск и трафик.
    DOWNLOADS = "downloads"

    #: Править привязки папок и серий, запускать сканирование библиотеки.
    LIBRARY = "library"

    #: Смотреть онлайн через наш прокси. Отдельно от загрузок намеренно: это
    #: и есть роль «пусть смотрит, но ничего не качает и не меняет».
    WATCH = "watch"

    #: Сохранять файлы себе на устройство — и с Anime365, и уже лежащие в
    #: библиотеке.
    #:
    #: Отдельно от `WATCH`, хотя ходят они через одни и те же маршруты
    #: `/api/stream/*`: посмотреть в браузере и унести файл с сервера — разные
    #: последствия. Первое ничего не оставляет, второе выносит наружу копию,
    #: и решать это должен отдельный переключатель.
    #:
    #: Отдельно от `DOWNLOADS` тоже: то право тратит диск и трафик сервера, а
    #: это — нет. Тот, кому можно унести серию себе, не обязан уметь занимать
    #: общий диск.
    DEVICE_DOWNLOADS = "device_downloads"


#: Права, которые есть у каждого вошедшего просто по факту входа.
#:
#: Решение пользователя, и оно верное: тот, кто может войти, обязан хоть
#: что-то видеть — иначе учётная запись есть, а смысла в ней нет. Раздавать
#: такое право руками значит добавить шаг, у которого один возможный исход.
#:
#: Хранить его в `permissions` записи при этом не нужно: право подставляется
#: при проверке. Так оно не может «потеряться» ни при правке записи, ни при
#: обновлении, где старые строки остались бы без него.
IMPLICIT_PERMISSIONS = frozenset({Permission.CATALOG.value})

#: Что получает обычный пользователь, если при создании ничего не выбрали.
#:
#: Решение пользователя: обычной учётной записи по умолчанию доступны каталог,
#: страницы тайтлов и сохранение себе на устройство. Каталог и тайтлы — это
#: `CATALOG`, он и так неявный, поэтому в списке остаются два права.
#:
#: `WATCH` здесь потому, что без него «просмотр тайтлов» упирается в кнопку,
#: которая ничего не делает: смотреть онлайн — обычное чтение, диска и общих
#: настроек оно не трогает. Ни одно из них не тратит ресурсы сервера, а всё,
#: что тратит (`DOWNLOADS`, `LIBRARY`, `SETTINGS`), по умолчанию выключено.
#:
#: Галочки в форме создания предзаполняются этим списком и снимаются вручную.
DEFAULT_PERMISSIONS = [Permission.WATCH.value, Permission.DEVICE_DOWNLOADS.value]

#: Полный набор — то, что вообще существует. Нужен для проверки входящих
#: значений; форма в интерфейсе строится по `ASSIGNABLE_PERMISSIONS`.
ALL_PERMISSIONS = [p.value for p in Permission]

#: Что показывать галочками в форме пользователя. Неявные права туда не
#: попадают: галочка, которую нельзя снять, только сбивает с толку.
ASSIGNABLE_PERMISSIONS = [p for p in ALL_PERMISSIONS if p not in IMPLICIT_PERMISSIONS]


class CurrentUser:
    """Кто выполняет запрос. Отдельный тип, чтобы не таскать модель из сессии БД."""

    def __init__(self, user_id: int, name: str, is_admin: bool, permissions: list[str]) -> None:
        self.id = user_id
        self.name = name
        self.is_admin = is_admin
        self.permissions = permissions

    def can(self, permission: Permission) -> bool:
        # У администратора прав не спрашивают: иначе достаточно забыть выдать
        # ему одну галочку, чтобы он потерял доступ к собственным настройкам.
        # Администратор здесь любой, а не только заданный окружением: флаг и
        # означает «может всё», а корневая учётная запись отличается лишь тем,
        # что этот флаг ей нельзя снять.
        if self.is_admin:
            return True
        # Неявные права не хранятся в записи — подставляем при проверке.
        return permission.value in self.permissions or permission.value in IMPLICIT_PERMISSIONS


#: Кем считать запрос, если пользователя определить не удалось.
#:
#: Так бывает штатно: пароль на вход не задан, и middleware сессию не заводит
#: вовсе. Раз пароля нет, разграничивать некого — доступ и так открыт всем, у
#: кого есть сеть до порта, и урезать права было бы имитацией защиты.
_FALLBACK = CurrentUser(DEFAULT_USER_ID, "default", is_admin=True, permissions=ALL_PERMISSIONS)


def current_user(request: Request) -> CurrentUser:
    user_id = getattr(request.state, "user_id", None)
    if user_id is None:
        return _FALLBACK

    with session_scope() as session:
        row = session.get(AppUser, user_id)
        if row is None:
            # Пользователя удалили, пока его сессия жива. Отказываем: тихо
            # выдать ему права по умолчанию значило бы восстановить доступ,
            # который только что отобрали.
            raise ApiError(
                403,
                errors.PERMISSION_DENIED,
                "Пользователь больше не существует — войдите заново",
            )
        return CurrentUser(row.id, row.name, row.is_admin, list(row.permissions or []))


def require(permission: Permission):
    """Зависимость эндпоинта: пускает дальше только с этим правом."""

    def guard(user: CurrentUser = Depends(current_user)) -> CurrentUser:
        if not user.can(permission):
            raise ApiError(
                403,
                errors.PERMISSION_DENIED,
                f"Недостаточно прав: требуется «{permission.value}»",
                permission=permission.value,
            )
        return user

    return guard


#: Значения, которые FastAPI считает истиной в булевом query-параметре.
#: Держим свой список, потому что проверка прав идёт до разбора параметров.
_TRUTHY = frozenset({"1", "true", "t", "yes", "y", "on"})


def require_save_or_watch():
    """Право зависит от того, играем файл или уносим его себе на диск.

    Один и тот же маршрут делает и то и другое, а разница — в параметре
    `download`. Разнести по разным маршрутам не выйдет: плееру и кнопке
    «сохранить» нужен один и тот же файл с одним и тем же разбором прав на
    путь, отличается только `Content-Disposition`.

    Проверять по маршруту здесь нельзя ни в одну сторону. Оставить `watch` —
    и файл унесёт тот, кому разрешён только просмотр. Поставить право на
    скачивание — и просмотр закроется у того, кто ничего не уносит.
    """

    def guard(request: Request, user: CurrentUser = Depends(current_user)) -> CurrentUser:
        saving = (request.query_params.get("download") or "").strip().lower() in _TRUTHY
        needed = Permission.DEVICE_DOWNLOADS if saving else Permission.WATCH
        if not user.can(needed):
            raise ApiError(
                403,
                errors.PERMISSION_DENIED,
                f"Недостаточно прав: требуется «{needed.value}»",
                permission=needed.value,
            )
        return user

    return guard


def require_admin():
    """Только администратор. Для управления самими пользователями."""

    def guard(user: CurrentUser = Depends(current_user)) -> CurrentUser:
        if not user.is_admin:
            raise ApiError(
                403,
                errors.ADMIN_REQUIRED,
                "Действие доступно только администратору",
            )
        return user

    return guard
