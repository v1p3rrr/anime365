import { useT, type TranslationKey } from './index'

/**
 * Подпись вида перевода на языке интерфейса.
 *
 * Виды приходят из API Anime365, и набор там шире описанного: кроме `voice`,
 * `sub` и `raw` встречался `subv`. Сервер приводит известные псевдонимы к нашим
 * трём (`services/translation_types.py`), но появиться может и такой, о котором
 * мы ещё не знаем.
 *
 * ⚠️ Без этой обёртки в интерфейсе печатался **сам ключ словаря** — строка
 * «Русский kind.subv1 авторов». Показывать код вида честнее: он короткий,
 * непонятен ровно настолько, насколько непонятен нам самим, и по нему можно
 * найти причину. Прятать такой перевод нельзя — он существует и скачивается.
 */
export function useKindLabel() {
  const { t } = useT()
  return (kind: string | null | undefined) => {
    if (!kind) return ''
    const key = `kind.${kind}` as TranslationKey
    const label = t(key)
    // t() возвращает сам ключ, когда перевода нет — значит вид нам незнаком.
    return label === key ? kind : label
  }
}
