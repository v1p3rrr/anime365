/**
 * Подписи языков.
 *
 * Сам флаг рисует компонент `components/Flag.tsx` — эмодзи-флаги не подошли:
 * в Windows системного шрифта для них нет, и Chrome показывает вместо картинки
 * две буквы. Здесь остался только текстовый код для мест, где JSX невозможен —
 * например, подписи вариантов в выпадающем списке Mantine принимают строку.
 */

/** Код языка заглавными: `ru` → `RU`. */
export function langCode(lang: string): string {
  return lang.toUpperCase()
}
